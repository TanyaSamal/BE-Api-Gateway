import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter } from 'k6/metrics';

const rateLimitedRequests = new Counter('rate_limited_429');

export const options = {
  stages: [
    { duration: '10s', target: 30 },
    { duration: '30s', target: 100 },
    { duration: '10s', target: 0 },
  ],
  thresholds: {
    http_req_duration: ['p(95)<500'],
    'http_req_failed{expected:true}': ['rate<0.01'],
  },
};

const BASE_URL = 'http://api-gateway:3001';

function generateCorrelationId(vu, iter) {
  return `k6-vu${vu}-iter${iter}-${Date.now()}`;
}

export default function () {
  const userId = 'user-1';
  const baseHeaders = {
    'Content-Type': 'application/json',
    'x-user-id': userId,
    'x-user-role': 'user',
  };

  // 1. Создание задачи
  const createPayload = JSON.stringify({
    title: `Load Test Task VU-${__VU} #${__ITER}`,
    description: 'Generated by k6 performance test',
  });

  const createRes = http.post(`${BASE_URL}/tasks`, createPayload, {
    headers: { ...baseHeaders, 'x-correlation-id': generateCorrelationId(__VU, __ITER) },
    tags: { expected: 'true', endpoint: 'create_task' },
  });

  check(createRes, {
    'POST /tasks status is 201': (r) => r.status === 201,
  });

  const taskId = createRes.status === 201 ? createRes.json('id') : null;

  sleep(0.2);

  // 2. Чтение и завершение задачи
  if (taskId) {
    const getRes = http.get(`${BASE_URL}/tasks/${taskId}`, {
      headers: { ...baseHeaders, 'x-correlation-id': generateCorrelationId(__VU, __ITER) },
      tags: { expected: 'true', endpoint: 'get_task' },
    });

    check(getRes, {
      'GET /tasks/:id status is 200': (r) => r.status === 200,
    });

    sleep(0.2);

    const completeRes = http.patch(`${BASE_URL}/tasks/${taskId}/complete`, null, {
      headers: { ...baseHeaders, 'x-correlation-id': generateCorrelationId(__VU, __ITER) },
      tags: { expected: 'true', endpoint: 'complete_task' },
    });

    check(completeRes, {
      'PATCH /tasks/:id/complete status is 200': (r) => r.status === 200,
    });
  }

  // 3. Аналитика с обязательными query-параметрами (userId и period)
  if (Math.random() < 0.2) {
    const analyticsRes = http.get(
      `${BASE_URL}/analytics/dashboard?userId=1&period=7_days`,
      {
        headers: { ...baseHeaders, 'x-correlation-id': generateCorrelationId(__VU, __ITER) },
        tags: { expected: 'false', endpoint: 'get_analytics' },
      },
    );


    if (analyticsRes.status === 429) {
      rateLimitedRequests.add(1);
    }

    check(analyticsRes, {
      'GET /analytics/dashboard is 200 or 429': (r) =>
        r.status === 200 || r.status === 429,
    });
  }

  sleep(0.5);
}
